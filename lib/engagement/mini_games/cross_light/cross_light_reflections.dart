List<String> get crossLightReflectionTemplates {
  final result = <String>[];
  for (final root in _reflectionRoots) {
    for (final closing in _reflectionClosings) {
      result.add('$root $closing');
    }
  }
  assert(result.length == 365);
  return List.unmodifiable(result);
}

String crossLightReflectionForDate(DateTime date) {
  final start = DateTime(date.year, 1, 1);
  final dayIndex = date.difference(start).inDays;
  return crossLightReflectionTemplates[dayIndex % 365];
}
