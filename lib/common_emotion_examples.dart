/// Card-bound starting suggestions. All source wording remains available in the full list.
List<String> commonCardExamples(String emotion,
    {int? intensity, int limit = 5}) {
  final all = commonEmotionExamples[emotion] ?? commonGenericSituationExamples;
  if (limit <= 0) return const [];
  if (emotion == '놀람' || emotion == '벅찬') {
    return const ['저는 반갑고 기쁜 느낌에 가까워요.', '저는 당황스럽고 버거운 느낌에 가까워요.']
        .take(limit)
        .toList();
  }
  final preferred = intensity != null && intensity <= 3
      ? commonLowIntensityExamples[emotion]
      : intensity != null && intensity >= 7
          ? commonHighIntensityExamples[emotion]
          : null;
  return <String>{
    ...?preferred,
    if (preferred == null) ...all,
    ...commonGenericSituationExamples,
  }.take(limit).toList(growable: false);
}
